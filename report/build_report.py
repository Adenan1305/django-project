def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    for c, text in zip(t.rows[0].cells, headers):
        c.text = text
        for r in c.paragraphs[0].runs: r.bold = True
    prop = OxmlElement('w:tblHeader')
    t.rows[0]._tr.get_or_add_trPr().append(prop)
    for row in rows:
        cells = t.add_row().cells
        for c, text in zip(cells, row): c.text = text
    for row in t.rows:
        for c in row.cells:
            for par in c.paragraphs:
                par.paragraph_format.space_after = Pt(5)
                par.paragraph_format.space_before = Pt(5)
                for r in par.runs: r.font.size = Pt(10)
    p('')
    return t

